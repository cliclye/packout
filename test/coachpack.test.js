// Builds a sample coach pack from a real finished event with the second half of quals "unplayed".
const fs = require('fs');
const R = __dirname + '/../src/shared/';
const { sampleMatches, samplePaths } = require(R + 'sample');
const { summarize } = require(R + 'analytics');
const D = require(R + 'deepstats');
const P = require(R + 'predict');
const { buildCoachPack } = require(R + 'coachpack');
const dir = process.argv[2] || '/tmp/ev';
const out = process.argv[3];
const j = (f) => JSON.parse(fs.readFileSync(`${dir}/${f}`, 'utf8'));
const all = j('2025wasno.json');
const quals = all.filter((m) => m.comp_level === 'qm').sort((a, b) => a.match_number - b.match_number);
const cut = Math.floor(quals.length * 0.55);
const masked = quals.map((m, i) => (i < cut ? m : { ...m, actual_time: null, winning_alliance: '', alliances: { red: { ...m.alliances.red, score: -1 }, blue: { ...m.alliances.blue, score: -1 } } }));
const teams = [...new Set(quals.flatMap((m) => [...m.alliances.red.team_keys, ...m.alliances.blue.team_keys].map((k) => k.slice(3))))];
const map = {};
['971', '1540', '2471', '2990', '2910', '1425', '254', '1678', '4414', '1323'].forEach((t, i) => (map[t] = teams[i]));
const recs = sampleMatches().map((r) => ({ ...r, teamNumber: map[r.teamNumber] }));
const paths = samplePaths().map((p) => ({ ...p, teamNumber: map[p.teamNumber] }));
const summaries = summarize(recs, [], paths);
const field = D.buildField(recs, paths, summaries);
const event = { info: j('info.json'), matches: masked, rankings: j('rank.json'), oprs: j('oprs.json'), teams: j('teams.json'), alliances: [], awards: [] };
const fit = P.fitModel(event.matches, recs, { tbaOprs: event.oprs });
const myTeam = (masked.slice(cut)[0].alliances.red.team_keys[0]).slice(3);
const comp = { name: 'Sample Event', eventKey: '2025wasno', schedule: [], paths, strategyNotes: {} };
const pack = buildCoachPack({ comp, summaries, field, event, fit, myTeam });
console.log('team', myTeam, 'matches', pack.matches.length, 'teams', Object.keys(pack.teams).length, 'plans', Object.keys(pack.plans).length, 'KB', Math.round(JSON.stringify(pack).length / 1024));
const first = Object.entries(pack.plans)[0];
console.log(first[0], first[1].pOurs, first[1].recs.map((r) => r.title).slice(0, 3));
if (out) fs.writeFileSync(out, JSON.stringify(pack, null, 1));
